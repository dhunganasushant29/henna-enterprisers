// Builds responsive WebP variants and a typed manifest for every photo in assets/photos.
// Run with `npm run images` after adding or replacing a photo.
import { readdir, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const SRC = here("../assets/photos/");
const OUT = here("../public/img/");
const MANIFEST = here("../src/data/images.ts");
const WIDTHS = [256, 384, 640, 828, 1080, 1600]; // keep in sync with next.config.ts + image-loader.ts

await mkdir(OUT, { recursive: true });
const files = (await readdir(SRC)).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort();
const entries = [];

for (const file of files) {
  const name = path.parse(file).name;
  const input = sharp(path.join(SRC, file));
  const { width, height } = await input.metadata();

  await Promise.all(
    WIDTHS.map((w) =>
      input
        .clone()
        .resize({ width: Math.min(w, width), withoutEnlargement: true })
        .webp({ quality: 80, effort: 6, alphaQuality: 90 }) // keeps transparency for cut-out portraits
        .toFile(path.join(OUT, `${name}-${w}.webp`)),
    ),
  );

  // ~300 byte blurred preview shown while the real image loads.
  const blur = await input.clone().resize(16).blur(1.2).webp({ quality: 40 }).toBuffer();
  entries.push({ name, width, height, blur: `data:image/webp;base64,${blur.toString("base64")}` });
  console.log(`✓ ${name} (${width}×${height})`);
}

const body = entries
  .map((e) => `  "${e.name}": { src: "/img/${e.name}", width: ${e.width}, height: ${e.height}, blurDataURL: "${e.blur}" },`)
  .join("\n");
await writeFile(
  MANIFEST,
  `// Generated by scripts/build-images.mjs. Do not edit by hand.\nexport const images = {\n${body}\n} as const;\n\nexport type ImageName = keyof typeof images;\n`,
);
