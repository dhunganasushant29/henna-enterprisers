// Generates the dotted region map used on the home page.
// Run once with `node scripts/build-map.mjs`; output is committed so builds stay offline-friendly.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

const world = JSON.parse(readFileSync(new URL("../node_modules/world-atlas/countries-50m.json", import.meta.url)));
const countries = feature(world, world.objects.countries).features;
const nepal = countries.find((c) => c.id === "524");

export const BOUNDS = { west: 30, east: 93, north: 37, south: 8 };
const W = 1000;
const kx = W / (BOUNDS.east - BOUNDS.west);
const ky = kx / Math.cos((25 * Math.PI) / 180);
const H = Math.round((BOUNDS.north - BOUNDS.south) * ky);
const project = ([lon, lat]) => [+((lon - BOUNDS.west) * kx).toFixed(1), +((BOUNDS.north - lat) * ky).toFixed(1)];

const STEP = 0.62;
let land = "";
let home = "";
for (let lat = BOUNDS.north; lat >= BOUNDS.south; lat -= STEP) {
  for (let lon = BOUNDS.west; lon <= BOUNDS.east; lon += STEP / 1.0) {
    const p = [lon, lat];
    const [x, y] = project(p);
    if (geoContains(nepal, p)) home += `M${x} ${y}h0`;
    else if (countries.some((c) => geoContains(c, p))) land += `M${x} ${y}h0`;
  }
}

mkdirSync(new URL("../public/map/", import.meta.url), { recursive: true });
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" fill="none" stroke-linecap="round"><path d="${land}" stroke="#fff" stroke-opacity=".3" stroke-width="4.6"/><path d="${home}" stroke="#ff4a55" stroke-width="5"/></svg>`;
writeFileSync(new URL("../public/map/region-dots.svg", import.meta.url), svg);

const cities = {
  kathmandu: [85.32, 27.71],
  mumbai: [72.88, 19.08],
  sharjah: [55.41, 25.35],
  jubail: [49.66, 27.0],
  kuwait: [47.98, 29.38],
  makkah: [39.83, 21.42],
};
const projected = Object.fromEntries(Object.entries(cities).map(([k, v]) => [k, project(v)]));
writeFileSync(
  new URL("../src/data/map.ts", import.meta.url),
  `// Generated by scripts/build-map.mjs. Do not edit by hand.\nexport const MAP_SIZE = { width: ${W}, height: ${H} } as const;\nexport const CITY_POINTS = ${JSON.stringify(projected, null, 2)} as const;\n`,
);
console.log({ W, H, svgKB: (svg.length / 1024).toFixed(1) });
